// يُعيد الاسم بالتشكيل إذا اختلف عن المُدخل، وإلا null (لا اقتراح).
export function vocalizeArabicName(input: string): string | null {
  const raw = (input ?? "").trim();
  if (!raw) return null;
  let changed = false;
  const out = raw
    .split(/(\s+)/)
    .map((token) => {
      if (/^\s+$/.test(token) || !token) return token;
      const hit = NAME_TASHKEEL[token];
      if (hit && hit !== token) {
        changed = true;
        return hit;
      }
      return token;
    })
    .join("");
  return changed ? out : null;
}
