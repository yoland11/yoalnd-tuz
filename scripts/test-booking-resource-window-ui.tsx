import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import * as React from "react";
import { renderToStaticMarkup } from "react-dom/server";
(globalThis as any).React = React;
assert.ok(existsSync("src/components/booking-resource-window-form.tsx"), "Booking Center must expose the canonical resource-period editor");
const { BookingResourceWindowForm } = await import("../src/components/booking-resource-window-form");
const shared=await import("../src/components/booking-resource-window-form") as any;
assert.equal(typeof shared.BookingResourceWindowInputs,"function","new photo forms must reuse the four accessible canonical time fields");
assert.equal(typeof shared.resourceWindowFromLocal,"function");
const local={preparationStart:"2026-10-22T12:00",eventStart:"2026-10-22T20:00",eventEnd:"2026-10-23T01:00",returnEnd:"2026-10-23T12:00"};
assert.equal(shared.resourceWindowFromLocal(local,"2026-10-22").eventStart,"2026-10-22T20:00:00+03:00");
assert.throws(()=>shared.resourceWindowFromLocal(local,"2026-10-25"),/يطابق/);
const data = { resourceWindow: null, expectedWindow: null, eventDate: "2026-10-22", eventTime: "20:00", canEdit: true };
const html = renderToStaticMarkup(<BookingResourceWindowForm data={data} onSave={async () => {}} />);
assert.match(html, /فترة تشغيل الموارد/);
for (const label of ["بداية التجهيز", "بداية المناسبة", "نهاية المناسبة", "اكتمال الإرجاع"]) assert.match(html, new RegExp(label));
assert.equal((html.match(/type="datetime-local"/g) ?? []).length, 4);
assert.match(html, /بغداد/); assert.match(html, /غير مكتملة/);
const reschedule=renderToStaticMarkup(<BookingResourceWindowForm data={{...data,canReschedule:true}} onSave={async()=>{}}/>);
assert.match(reschedule,/تعديل موعد الحجز مع فترة الموارد/,"calendar edits must have an explicit opt-in rather than silently changing the old period-save behavior");
assert.doesNotMatch(html, /100%|لا توجد تعارضات|جاهز للتنفيذ/);
const viewOnly = renderToStaticMarkup(<BookingResourceWindowForm data={{ ...data, canEdit: false }} onSave={async () => {}} />);
assert.doesNotMatch(viewOnly, /type="submit"/);
const error = renderToStaticMarkup(<BookingResourceWindowForm error={new Error("تعذر قراءة المواعيد")} onRetry={() => {}} onSave={async () => {}} />);
assert.match(error, /role="alert"/); assert.match(error, /إعادة المحاولة/); assert.doesNotMatch(error, /لا توجد/);
assert.match(renderToStaticMarkup(<BookingResourceWindowForm loading onSave={async () => {}} />), /تحميل فترة تشغيل الموارد/);
console.log("PASS real resource-period form: four explicit labelled times, Baghdad, view-only, loading and explicit read errors");
