import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { PgDialect } from "drizzle-orm/pg-core";
assert.ok(existsSync("src/server/booking-daily-operations.ts"), "authorized bounded daily loader must exist");
const { loadDailyOperations } = await import("../src/server/booking-daily-operations");
const filters = { period: "today" as const, search: "", category: "all", status: "all", employee: null, vehicle: null, location: "" };
const now = new Date("2026-10-18T12:00:00Z");
let reads = 0;
const seen: ReturnType<PgDialect["sqlToQuery"]>[] = [];
const row = { source: "kosha", id: 12, number: "AJN-KOSHA-0012", customer_name: "أحمد", event_date: "2026-10-18", event_time: "18:00", location: "بغداد", status: "new", category: "kosha", details: {}, assigned_staff_id: 8, vehicle_id: null, vehicle_name: null, transportation_mode: "customer", crew_name: null };
const executor = { async execute(query: any) {
  const built = new PgDialect().sqlToQuery(query); seen.push(built); reads++;
  if (reads === 1) return { rows: [row] };
  if (reads === 2) return { rows: [] };
  if (reads === 3) return { rows: [{ source_type: "kosha_booking", source_id: 12, overdue_tasks: 2, open_tasks: 3 }] };
  return { rows: [{ id: 8, full_name: "حسين" }] };
} };
const result = await loadDailyOperations(executor, filters, ["kosha"], now);
assert.equal(result.rows[0].staff[0].name, "حسين");
assert.equal(result.summary.overdueTasks, 2);
assert.ok(seen[0].params.includes("2026-10-18") && seen[0].params.includes("2026-10-19"));
assert.match(seen[0].sql, /limit\s+\$\d+/i, "base query bounded before detail reads");
assert.ok(seen[0].params.includes(501));
assert.ok(!seen[0].sql.includes("FROM service_orders"), "disallowed booking source is never queried");
assert.match(seen[1].sql, /source_type/, "facts are source-scoped not numeric ID only");
assert.ok(seen[1].params.includes("kosha_booking") && seen[1].params.includes(12));
assert.equal(result.rows[0].openTasks, 3);
let emptyReads = 0;
const empty = await loadDailyOperations({ execute: async () => { emptyReads++; return { rows: [] }; } }, filters, ["service"], now);
assert.equal(empty.rows.length, 0);
assert.equal(emptyReads, 1, "empty successful cohort needs no unbounded detail queries");
await assert.rejects(loadDailyOperations({ execute: async () => { throw new Error("connection failed"); } }, filters, ["kosha"], now), /connection failed/, "database failure is never empty data");
await assert.rejects(loadDailyOperations(executor, filters, [], now), /صلاحية/);
console.log("PASS daily operations bounded source-scoped SQL, real facts, names and failure propagation");
