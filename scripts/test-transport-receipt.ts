import assert from "node:assert/strict";
import { buildTransportReceiptHtml,DEFAULT_TRANSPORT_RECEIPT_SETTINGS,normalizeTransportReceiptSettings,type TransportReceiptData } from "../src/lib/transport-receipt";
const data:TransportReceiptData={receiptReference:"B-7-T01",bookingNumber:"B-7",variant:"customer",company:{name:"شركة الاختبار",phone:"07712345678",logoUrl:"javascript:alert(1)"},customerName:'عميل <script>alert("x")</script>',customerPhone:"07710000000",transportType:"نقل كوشة",origin:"المخزن",destination:"القاعة",transportDate:"2026-10-24",departureTime:"10:00",expectedArrivalTime:null,driverName:"سائق",driverPhone:null,vehicleName:"مركبة",vehiclePlate:"1234",assignedWork:null,notes:"ملاحظة طويلة ".repeat(60),status:null,amount:{value:50000,label:"أجرة النقل الكلية للحجز"},driverSettlement:null,qrUrl:"https://example.test/admin/bookings/service/7?tab=overview"};
const html=buildTransportReceiptHtml(data,DEFAULT_TRANSPORT_RECEIPT_SETTINGS,1);
assert.match(html,/size:\s*80mm auto/);
assert.match(html,/width:\s*80mm/);
assert.match(html,/padding:\s*1mm 4mm/,"4mm hardware side margins, little paper above and below");
assert.match(html,/ajn-r--compact/,"the trip receipt is the short slip");
assert.match(html,/dir="rtl"/);
assert.match(html,/أجرة النقل الكلية للحجز/);
assert.match(html,/50,000/);
assert.ok(!html.includes('عميل <script>'));
assert.ok(html.includes('&lt;script&gt;'));
assert.ok(!html.includes('src="javascript:'));
assert.match(html,/overflow-wrap:\s*anywhere/);
assert.doesNotMatch(html,/غير مسجل/,"facts that were not recorded are left out");
const plain=html.replace(/[\u2068\u2069]/g,"");
assert.match(plain,/من المخزن إلى القاعة/,"origin and destination share one line");
assert.match(plain,/مركبة · 1234/,"vehicle and plate share one line");
assert.match(plain,/2026-10-24 · 10:00/,"date and time share one line");
assert.doesNotMatch(html,/الوصول المتوقع|هاتف السائق|رقم الحجز/,"empty or repeated facts are not printed");
assert.match(html,/ملاحظة طويلة/,"notes print when they exist");
assert.doesNotMatch(buildTransportReceiptHtml({...data,notes:null},DEFAULT_TRANSPORT_RECEIPT_SETTINGS,1),/ملاحظات/,"no empty notes block");
assert.match(html,/beforeprint/);
assert.equal((html.match(/data-copy="/g)||[]).length,1);
assert.equal((buildTransportReceiptHtml(data,DEFAULT_TRANSPORT_RECEIPT_SETTINGS,3).match(/data-copy="/g)||[]).length,3);
for(const copies of [0,-1,6,1.5,NaN])assert.throws(()=>buildTransportReceiptHtml(data,DEFAULT_TRANSPORT_RECEIPT_SETTINGS,copies));
const driver=buildTransportReceiptHtml({...data,variant:"driver"},DEFAULT_TRANSPORT_RECEIPT_SETTINGS,1);
assert.ok(!driver.includes("50,000"),"renderer independently prevents customer charge on driver copy");
assert.match(driver,/وصل السائق/);
assert.doesNotMatch(driver,/غير مسجل|مستحق السائق/,"the driver copy has no empty settlement line");
const hidden=buildTransportReceiptHtml(data,normalizeTransportReceiptSettings({showCustomer:false,showAmount:false,showNotes:false,showCompanyName:false}),1);
assert.ok(!hidden.includes("عميل &lt;script&gt;"));assert.ok(!hidden.includes("07710000000"));assert.ok(!hidden.includes("50,000"));assert.ok(!hidden.includes("ملاحظة طويلة"));assert.ok(!hidden.includes("شركة الاختبار"));
assert.throws(()=>normalizeTransportReceiptSettings({showAmount:"true"}));
assert.throws(()=>normalizeTransportReceiptSettings([]));
assert.throws(()=>normalizeTransportReceiptSettings({grantFinancialAccess:true}));
assert.equal(normalizeTransportReceiptSettings(undefined).showAmount,true);
console.log("PASS transport thermal renderer: short 80mm RTL slip, hardware padding, only recorded facts on merged lines, escaped text, copy bounds, driver privacy, field settings and measured-height hook");
