import assert from "node:assert/strict";
import { printTransportDocument } from "../src/lib/transport-print";
let opens=0,closed=0,audits=0,blocked=false,auditFails=false;
const documents:string[]=[];
const popup:any={closed:false,close:()=>{closed++;popup.closed=true},document:{open:()=>{},write:(html:string)=>documents.push(html),close:()=>{},images:[],fonts:{ready:Promise.resolve()}}};
(globalThis as any).window={open:()=>{opens++;if(blocked)return null;popup.closed=false;return popup}};
await printTransportDocument("<html><body>وصل</body></html>",async()=>{audits++});
assert.equal(opens,1,"reuse synchronously opened window rather than a second blocked popup");
assert.equal(audits,1);assert.ok(documents.at(-1)?.includes("waitForImages"),"reuse existing AJN printer/desktop script");
blocked=true;
await assert.rejects(()=>printTransportDocument("<body>وصل</body>",async()=>{audits++}),/نافذة|منبثق/);
assert.equal(audits,1,"blocked popup is not a print request");blocked=false;
const before=documents.length;
await assert.rejects(()=>printTransportDocument("<body>وصل</body>",async()=>{auditFails=true;throw Error("audit unavailable")}),/audit unavailable/);
assert.ok(auditFails);assert.equal(documents.length,before+1,"audit failure must not inject auto-print");assert.ok(closed>0);
popup.document.images=[{complete:true,naturalWidth:0}];
await assert.rejects(()=>printTransportDocument("<body>وصل</body>",async()=>{audits++}),/صور|صورة/);
assert.equal(audits,1,"broken receipt assets must not be silently treated as printable");
console.log("PASS transport print orchestration: existing helper, one popup, audit gate, blocked popup and asset failures remain visible");
