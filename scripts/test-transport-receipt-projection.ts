import assert from "node:assert/strict";
import { PgDialect } from "drizzle-orm/pg-core";
import { readTransportReceipt,projectVehicleTransportBooking } from "../src/server/booking-transport-receipt";
import { readTransportPlan,validateTransportPlan } from "../src/lib/booking-transport-plan";
const dialect=new PgDialect();
const legacy={mode:"ajn",fee:50000,inTotal:true,vehicleId:5,driverId:8,note:"ملاحظة النقل فقط"};
const view=readTransportPlan({source:"service",id:7,bookingNumber:"B-7",legacy,storedPlan:null});
let stored:any=null,denyReads=false;
const executor={execute:async(statement:any)=>{
  if(denyReads)throw Error("unauthorized request must not read");
  const q=dialect.sqlToQuery(statement),sql=q.sql.toLowerCase();
  if(sql.includes("from service_orders"))return {rows:q.params.includes(7)?[{id:7,tracking_code:"AJN-1234-ABCDEF0123456789",customer_name:"عميل عربي",phone:"07710000000",event_date:"2026-10-24",details:{adminNotes:"PRIVATE ADMIN",bookingOperations:{transportation:legacy,transportPlan:stored}}}]:[]};
  if(sql.includes("from fleet_vehicles"))return {rows:[{id:5,name:"مركبة",plate_number:"1234"}]};
  if(sql.includes("from staff"))return {rows:[{id:8,full_name:"سائق عربي",username:"driver",phone:null}]};
  throw Error("Unexpected receipt SQL "+sql);
}};
const ref={source:"service" as const,id:7};
const access={canView:true,canViewCustomerCharge:true,company:{name:"AJN configured",phone:"07720000000",logoUrl:null},origin:"https://example.test"};
const customer=await readTransportReceipt(executor,ref,{tripId:"legacy-1",variant:"customer"},access);
assert.equal(customer.bookingNumber,"B-7-1234","reuse short public display reference, not bearer tracking code");
assert.equal(customer.receiptReference,"B-7-1234-T01");
assert.equal(customer.amount?.value,50000);
assert.match(customer.amount!.label,/الكلية/);
assert.equal(customer.driverName,"سائق عربي");
assert.equal(customer.driverPhone,null,"do not invent a staff phone");
assert.equal(customer.origin,null);
assert.equal(customer.departureTime,null,"event date/time is not transport departure");
assert.equal(customer.company.name,"AJN configured");
assert.ok(!JSON.stringify(customer).includes("PRIVATE ADMIN"));
assert.ok(!JSON.stringify(customer).includes("ABCDEF0123456789"),"public bearer token never leaves receipt projection");
const driver=await readTransportReceipt(executor,ref,{tripId:"legacy-1",variant:"driver"},access);
assert.equal(driver.amount,null);
assert.equal(driver.driverSettlement,null,"no inferred payable from the customer's fee");
assert.ok(!JSON.stringify(driver).includes("50000"),"driver DTO must not carry a hidden customer charge");
assert.ok(driver.qrUrl?.startsWith("https://example.test/admin/bookings/service/7?"));
await assert.rejects(()=>readTransportReceipt(executor,ref,{tripId:"forged-trip",variant:"customer"},access),(e:any)=>e.status===404);
await assert.rejects(()=>readTransportReceipt(executor,{...ref,id:8},{tripId:"legacy-1",variant:"customer"},access),(e:any)=>e.status===404);
await assert.rejects(()=>readTransportReceipt(executor,ref,{tripId:"legacy-1",variant:"customer"},{...access,canViewCustomerCharge:false}),(e:any)=>e.status===403);
denyReads=true;
await assert.rejects(()=>readTransportReceipt(executor,ref,{tripId:"legacy-1",variant:"driver"},{...access,canView:false}),(e:any)=>e.status===403);
denyReads=false;
stored={trips:"broken"};
await assert.rejects(()=>readTransportReceipt(executor,ref,{tripId:"legacy-1",variant:"driver"},access));
stored=null;
const per=validateTransportPlan({...view,feeMode:"per_trip",overallCharge:null,trips:[{...view.trips[0],customerCharge:30000},{...view.trips[0],id:"t2",sequence:2,vehicleId:6,customerCharge:20000}]});
const projected=projectVehicleTransportBooking(per,5,{paid:100000,total:200000,approvedExpense:10000});
assert.equal(projected.customerCharge,30000);
assert.equal(projected.transportRevenue,15000);
assert.equal(projected.expense,10000);
assert.equal(projected.customerCharge,30000);
assert.equal(projected.profit,20000,"vehicle income is the full recorded fee, not the collected share");
assert.equal(projectVehicleTransportBooking(per,5,{paid:0,total:200000,approvedExpense:45000}).profit,-15000,"a trip loss stays signed");
assert.equal(projected.operations.length,1);
const overall=validateTransportPlan({...per,feeMode:"overall",overallCharge:50000,trips:per.trips.map(t=>({...t,customerCharge:null}))});
const unknown=projectVehicleTransportBooking(overall,5,{paid:100000,total:200000,approvedExpense:10000});
assert.equal(unknown.customerCharge,null,"overall multi-vehicle fee is unallocated, not a fee per vehicle");
assert.equal(unknown.transportRevenue,null);
assert.equal(unknown.profit,null);
assert.equal(unknown.expense,10000,"one existing expense remains one expense");
console.log("PASS transport receipt projection: private token/notes redaction, driver privacy, identity/permission checks, optional fields and multi-vehicle fee allocation");
