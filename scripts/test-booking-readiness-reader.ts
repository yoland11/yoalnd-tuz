import assert from "node:assert/strict";
import {existsSync} from "node:fs";
import {PgDialect} from "drizzle-orm/pg-core";
import {projectDailyBooking} from "../src/lib/booking-daily-operations";
const row={source:"kosha" as const,id:12,number:"K-12",customerName:"أحمد",eventDate:"2020-01-01",eventTime:null,location:"بغداد",status:"new",category:"kosha",details:{},assignedStaffId:null,vehicleId:null,vehicleName:null,transportationMode:"customer",crewName:null,overdueTasks:0,openTasks:0,products:[]};
const projection=projectDailyBooking(row);
assert.ok(Array.isArray((projection.readiness as any).blockers),"daily projection must use the shared mandatory evidence evaluator");
assert.equal(projection.readiness.status,"not_ready","unknown mandatory checks are not execution-ready");
assert.ok(existsSync("src/server/booking-operational-readiness.ts"),"missing bounded exact-booking readiness reader");
const {loadBookingReadiness}=await import("../src/server/booking-operational-readiness");
const queries:ReturnType<PgDialect["sqlToQuery"]>[]=[];
const executor={async execute(sql:any){
  const q=new PgDialect().sqlToQuery(sql);queries.push(q);
  if(queries.length===1) return {rows:[{source:"kosha",id:12,number:"K-12",customer_name:"أحمد",event_date:"2020-01-01",event_time:null,location:"بغداد",status:"new",category:"kosha",details:{},transportation_mode:"customer"},{source:"service",id:12,number:"S-12",customer_name:"علي",event_date:null,event_time:null,location:null,status:"new",category:"photography",details:{},transportation_mode:null}]};
  return {rows:[]};
}};
const result=await loadBookingReadiness(executor,[{source:"kosha",id:12},{source:"service",id:12}],new Date("2026-10-18T12:00:00Z"));
assert.equal(result.size,2);
assert.equal(result.get("kosha:12")?.checks.find(c=>c.id==="location")?.state,"pass");
assert.equal(result.get("service:12")?.checks.find(c=>c.id==="location")?.state,"fail");
assert.equal(result.get("service:12")?.checks.find(c=>c.id==="date")?.state,"unknown","legacy missing event dates still receive explicit evidence");
assert.ok(queries[0].params.includes(12));assert.ok(queries[0].params.includes("kosha"));assert.ok(queries[0].params.includes("service"));
assert.ok(!queries[0].params.includes("2026-10-18"),"exact ID reads must not be capped by today's date horizon");
assert.match(queries[0].sql,/\(source,\s*id\) IN/i);
await assert.rejects(()=>loadBookingReadiness(executor,[{source:"kosha",id:-1}]),/Invalid/);
await assert.rejects(()=>loadBookingReadiness(executor,Array.from({length:1001},(_,i)=>({source:"kosha" as const,id:i+1}))),/limit/);
await assert.rejects(()=>loadBookingReadiness({execute:async()=>{throw new Error("read failed")}},[{source:"kosha",id:12}]),/read failed/);
assert.equal((await loadBookingReadiness(executor,[])).size,0);
console.log("PASS shared original facts, exact old/missing-date refs, source isolation, limits and error propagation");
